#!/usr/bin/env python3
"""Build references/bau-top-30.md from the diggerlid-mer /api/ads JSON.

Usage:
  curl -s "https://diggerlid-mer.vercel.app/api/ads" > top-ads.json
  python3 scripts/analyse_top_ads.py top-ads.json

Measures length, emoji use, structure and style across the top BAU ads, then writes
the stats plus every ad's copy into references/bau-top-30.md. Aggregate ad data only.
"""
import json, re, sys, statistics as st
from collections import Counter
from pathlib import Path

EMOJI = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF⬆⬇⭐⭕⌚-⏿⤴⤵〰〽]️?"
)
URL = re.compile(r"(https?://\S+|diggerlid\.com\S*)", re.I)


def body_variants(ad):
    c = ad.get("copy") or {}
    bodies = [b for b in ([c.get("body")] + (c.get("bodies") or [])) if b]
    seen, out = set(), []
    for b in bodies:
        if b not in seen:
            seen.add(b)
            out.append(b)
    return out


def measure(text):
    lines = [l for l in text.splitlines() if l.strip()]
    first = lines[0] if lines else ""
    emojis = EMOJI.findall(text)
    return {
        "chars": len(text),
        "words": len(text.split()),
        "lines": len(lines),
        "emoji": len(emojis),
        "emoji_list": emojis,
        "opener_emoji": bool(EMOJI.match(first.strip())),
        "first_line": first.strip(),
        "first_125": text[:125],
        "question_hook": "?" in first,
        "checklist_lines": sum(1 for l in lines if EMOJI.match(l.strip()) and l is not first),
        "has_url": bool(URL.search(text)),
        "shop_now": "shop now" in text.lower(),
        "em_dash": "\u2014" in text,
        "free_ship": "free ship" in text.lower(),
        "warranty": "warranty" in text.lower(),
        "caps_words": len(re.findall(r"\b[A-Z]{3,}\b", text)),
        "exclaim": text.count("!"),
    }


def med(xs):
    return round(st.median(xs), 1) if xs else 0


def pct(n, d):
    return f"{round(100 * n / d)}%" if d else "n/a"


def main(path):
    data = json.loads(Path(path).read_text())
    if data.get("error"):
        sys.exit("API error: " + data["error"])
    ads = data.get("ads", [])
    rows = []
    for a in ads:
        for b in body_variants(a)[:1]:  # primary body per ad for stats
            rows.append((a, measure(b)))
    n = len(rows)
    if not n:
        sys.exit("No ads with copy in file.")
    M = [m for _, m in rows]
    titles = [t for a in ads for t in ([(a.get("copy") or {}).get("title")] + ((a.get("copy") or {}).get("titles") or [])) if t]
    descs = [t for a in ads for t in ([(a.get("copy") or {}).get("description")] + ((a.get("copy") or {}).get("descriptions") or [])) if t]
    emo = Counter(e for m in M for e in m["emoji_list"])
    openers = Counter(EMOJI.match(m["first_line"]).group(0) for m in M if m["opener_emoji"])
    chars = sorted(m["chars"] for m in M)
    tiers = Counter("Short (<250)" if c < 250 else "Medium (250-600)" if c <= 600 else "Long (>600)" for c in chars)

    out = []
    w = out.append
    w("# BAU Top Ads: Measured Copy Stats\n")
    w(f"Source: diggerlid-mer `/api/ads`, sorted by **{data.get('sort')}**, min spend ${data.get('min_spend')}, "
      f"windows {', '.join(':'.join(x) for x in data.get('windows', []))}. Ads analysed: **{n}**.\n")
    w("Generated by `scripts/analyse_top_ads.py`. This file overrides the length and emoji defaults in SKILL.md.\n")
    w("## Length\n")
    w(f"- Characters: median **{med(chars)}**, range {chars[0]} to {chars[-1]}, middle half {chars[n // 4]} to {chars[(3 * n) // 4]}")
    w(f"- Words: median {med([m['words'] for m in M])}. Non-empty lines: median {med([m['lines'] for m in M])}")
    w("- Tier mix: " + ", ".join(f"{k} {v}" for k, v in tiers.most_common()))
    w(f"- Headlines: median {med([len(t) for t in titles])} chars across {len(titles)}. Descriptions: median {med([len(t) for t in descs])} chars across {len(descs)}\n")
    w("## Emoji\n")
    w(f"- Emoji per ad: median **{med([m['emoji'] for m in M])}**, max {max(m['emoji'] for m in M)}. Ads with zero emoji: {sum(1 for m in M if m['emoji'] == 0)}")
    w(f"- Opens on an emoji: {pct(sum(m['opener_emoji'] for m in M), n)}. Most common openers: " + " ".join(f"{e}×{c}" for e, c in openers.most_common(8)))
    w("- Most used emoji overall: " + " ".join(f"{e}×{c}" for e, c in emo.most_common(15)))
    w(f"- Emoji checklist present (3+ emoji-led lines): {pct(sum(m['checklist_lines'] >= 3 for m in M), n)}\n")
    w("## Structure and style\n")
    w(f"- Question hook: {pct(sum(m['question_hook'] for m in M), n)}")
    w(f"- URL in body: {pct(sum(m['has_url'] for m in M), n)}. 'Shop Now' in body: {pct(sum(m['shop_now'] for m in M), n)}")
    w(f"- Mentions free shipping: {pct(sum(m['free_ship'] for m in M), n)}. Mentions warranty: {pct(sum(m['warranty'] for m in M), n)}")
    w(f"- Exclamation marks per ad: median {med([m['exclaim'] for m in M])}. ALL-CAPS words per ad: median {med([m['caps_words'] for m in M])}")
    w(f"- Em dashes found: {sum(m['em_dash'] for m in M)} ads (rule: none in new copy)\n")
    w("## Top ads (performance and copy)\n")
    w("| # | Ad | Spend | Purch | ROAS | CTR | Chars | Emoji | Hook (first line) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for i, (a, m) in enumerate(rows, 1):
        hook = m["first_line"].replace("|", "/")[:70]
        w(f"| {i} | {a.get('ad_name', '')[:40]} | ${a.get('spend')} | {a.get('purchases')} | {a.get('roas')}x | {a.get('ctr')}% | {m['chars']} | {m['emoji']} | {hook} |")
    w("\n## Full copy\n")
    for i, (a, m) in enumerate(rows, 1):
        c = a.get("copy") or {}
        w(f"### {i}. {a.get('ad_name', '')} · {a.get('roas')}x ROAS · {a.get('purchases')} purchases")
        w(f"Campaign: {a.get('campaign', '')} · Format: {c.get('format')} · Link: {c.get('link')}\n")
        for b in body_variants(a):
            w("```\n" + b.strip() + "\n```")
        hs = [t for t in [c.get("title")] + (c.get("titles") or []) if t]
        ds = [t for t in [c.get("description")] + (c.get("descriptions") or []) if t]
        if hs:
            w("Headlines: " + " · ".join(dict.fromkeys(hs)))
        if ds:
            w("Descriptions: " + " · ".join(dict.fromkeys(ds)))
        w("")
    dest = Path(__file__).resolve().parent.parent / "references" / "bau-top-30.md"
    dest.write_text("\n".join(out) + "\n")
    print(f"Wrote {dest} ({n} ads)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "top-ads.json")
